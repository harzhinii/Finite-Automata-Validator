import streamlit as st

from automata.catalog import get_catalog
from ui.common import show_diagram, show_table


def render() -> None:
    st.title("Automata Visualizer")
    st.caption("Every diagram is generated from the real transition systems (delta tables) in the code.")
    items = get_catalog()
    names = [d.title for d in items]
    choice = st.selectbox("Choose an automaton", names)
    d = items[names.index(choice)]
    st.write(d.caption)
    if d.large:
        st.warning("This machine is large; the browser view may be slow and dense. For a readable picture open "
                   f"`diagrams/{d.key}.svg` (generated by `python generate_assets.py`) and zoom.")
        if not st.checkbox("Render it here anyway", key=f"big_{d.key}"):
            if d.table:
                with st.expander("Transition table"):
                    show_table(d.table())
            return
    show_diagram(d.build(theme="dark"), d.build(theme="light"), key=d.key)
    st.caption("Double circle = accepting · arrow from 'start' = start state · dashed red = trap/dead state · Σ = every symbol · ε = empty move")
    if d.table:
        with st.expander("Transition table", expanded=True):
            show_table(d.table())
