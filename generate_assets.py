"""
generate_assets.py - Build every result file from the real implementation.

    python generate_assets.py            -> diagrams/*.png|svg  +  results/*.csv|json
    python generate_assets.py --no-pytest   (skip running pytest for results/pytest_output.txt)

Needs the Graphviz program `dot` for the image files (see README for installation).
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

from automata.catalog import get_catalog
from automata.visualize import graphviz_available, render_bytes
from validation.runner import write_results

ROOT = Path(__file__).resolve().parent


def make_diagrams() -> list[str]:
    out = ROOT / "diagrams"
    out.mkdir(exist_ok=True)
    if not graphviz_available():
        print("!! Graphviz 'dot' program not found - diagrams NOT generated. See README (Installation).")
        return []
    written = []
    for d in get_catalog():
        png = d.build(theme="light", dpi=60 if d.large else 200)
        (out / f"{d.key}.png").write_bytes(render_bytes(png, "png"))
        (out / f"{d.key}.svg").write_bytes(render_bytes(d.build(theme="light"), "svg"))
        written.append(d.key)
        print(f"   diagram: diagrams/{d.key}.png / .svg")
    return written


def write_report_tables(report) -> None:
    """results/report_tables.md: ready-to-paste Table 2, Table 4 and state counts (all measured)."""
    from automata.email_automata import get_email_system
    from automata.password_automata import get_password_system
    pw, em = get_password_system(), get_email_system()
    c = em.stage_counts
    lines = ["# Numbers for the report (generated by generate_assets.py - do not edit by hand)", "",
             "## Table 2 - Password policy: three equivalent designs", "", pw.design_table().to_markdown(index=False), "",
             "## E-mail automaton state counts (Fig. 3 caption)", "",
             f"* NFA: **{c['nfa_states']}** states ({len(em.nfa.epsilon_transitions())} ε-transitions)",
             f"* Subset DFA: **{c['subset_dfa_states']}** states ({c['subset_dfa_states_excluding_trap']} + trap ∅)",
             f"* Minimal DFA: **{c['minimal_dfa_states']}** states ({c['minimal_dfa_states_excluding_trap']} + trap)",
             "* Merged: " + ("; ".join(f"{m} = {' ≡ '.join(g)}" for m, g in em.minimal.merged_groups) or "nothing"), "",
             "## Table 4 - Test results", "", report.summary.drop(columns=["Individual cases"]).to_markdown(index=False), "",
             f"Total: {report.totals['tests']:,} tests, {report.totals['passed']:,} passed, {report.totals['failed']:,} failed "
             f"({report.totals['pass_percent']}%). Random tests use seed {report.totals['seed']}.", ""]
    (ROOT / "results" / "report_tables.md").write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    print("1/3  Running all validation tests and writing results/ ...")
    report = write_results(ROOT / "results")
    t = report.totals
    write_report_tables(report)
    print(f"     tests={t['tests']:,} passed={t['passed']:,} failed={t['failed']:,} pass%={t['pass_percent']}")
    print("2/3  Drawing diagrams from the real automata ...")
    make_diagrams()
    if "--no-pytest" not in sys.argv:
        print("3/3  Running pytest -> results/pytest_output.txt")
        proc = subprocess.run([sys.executable, "-m", "pytest", "-v", "--tb=short"], cwd=ROOT,
                              capture_output=True, text=True)
        (ROOT / "results" / "pytest_output.txt").write_text(proc.stdout + proc.stderr, encoding="utf-8")
        print("     " + (proc.stdout.strip().splitlines() or ["(no output)"])[-1])
        return proc.returncode
    return 0 if t["failed"] == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
